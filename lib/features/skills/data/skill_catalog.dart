  static SkillCatalogEntry _entry(
    String discipline,
    String name,
    MeasurementType measurementType,
    PerformanceType performanceType,
    String defaultUnit,
    List<String> allowedUnits, {
    String summary = '',
    String subdiscipline = '',
    bool supportsVariants = false,
    List<SkillCatalogVariant> variants = const [],
    List<String> aliases = const [],
    List<String> tags = const [],
    List<String> equipmentOptions = const [],
    bool isActive = true,
  }) {
    return SkillCatalogEntry(
      id: _slug(discipline, name),
      name: name,
      discipline: discipline,
      subdiscipline: subdiscipline,
      summary: summary,
      defaultUnit: defaultUnit,
      allowedUnits: allowedUnits,
      measurementType: measurementType,
      performanceType: performanceType,
      supportsVariants: supportsVariants,
      variants: variants,
      aliases: aliases,
      tags: tags,
      equipmentOptions: equipmentOptions,
      isActive: isActive,
    );
  }

