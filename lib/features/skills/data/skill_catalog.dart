  static List<String> get catalogDisciplines {
    return all.map((e) => e.discipline).toSet().toList()..sort();
  }

  static List<SkillCatalogEntry> get active =>
      all.where((e) => e.isActive || e.isCustom).toList();

  static List<SkillCatalogEntry> get popular {
    final preferred = active.where((e) => !e.isCustom).toList();
    return preferred.take(120).toList();
  }

  static SkillCatalogEntry? findById(String id) {
    for (final entry in all) {
      if (entry.id == id) return entry;
    }
    return null;
  }

  /// Search the catalog.
  ///
  /// Empty query returns active skills only (curated browsing).
  /// Non-empty query searches the full catalog, including inactive skills.
  static List<SkillCatalogEntry> search({
    String query = '',
    String? discipline,
    bool includeInactive = false,
  }) {
    final q = query.trim();
    final allowInactive = includeInactive || q.isNotEmpty;

    return all.where((entry) {
      if (discipline != null &&
          entry.discipline != discipline &&
          !entry.tags.contains(discipline)) {
        return false;
      }
      if (!allowInactive && !entry.isActive && !entry.isCustom) return false;
      return entry.matchesQuery(q);
    }).toList();
  }
